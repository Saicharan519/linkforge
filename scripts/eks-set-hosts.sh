#!/usr/bin/env bash
# eks-set-hosts.sh: phase 2 of the HTTP-mode deployment (P9.3). The two ALBs exist now; tell the app their DNS names.
#
#   scripts/eks-set-hosts.sh                       read both names from the cluster (needs KUBECONFIG, see eks-common.sh)
#   scripts/eks-set-hosts.sh APP_DNS GO_DNS        or give them (no cluster needed; used by the offline test)
#   add --no-push to commit without pushing
#
# It first CHECKS the assumption the whole HTTP mode rests on: the two Ingresses got two DIFFERENT load balancers. If they
# got the same name (or one is missing) it stops and changes nothing.
#
# Then it writes into envs/eks/values.yaml:
#   SHORT_URL_BASE        http://<go ALB name>      what the UI shows as the short link
#   PUBLIC_REDIRECT_HOST  <go ALB name>             the host on which the API serves ONLY redirects (host guard, D63)
#   ALLOWED_ORIGINS       http://<app ALB name>     the one origin allowed to make state-changing requests (CSRF)
# commits and pushes. Argo CD rolls the pods once; the ALBs are not touched.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/eks-common.sh"

GITOPS="${GITOPS_DIR:-$HOME/linkforge-gitops}"
PUSH=1
args=()
for arg in "$@"; do
  case "$arg" in
    --no-push) PUSH=0 ;;
    -*) die "unknown option: $arg" ;;
    *) args+=("$arg") ;;
  esac
done

if [ "${#args[@]}" -eq 0 ]; then
  step "reading the ALB names from the cluster"
  require_eks_cluster
  app_dns="$(ek -n linkforge get ingress app -o jsonpath='{.status.loadBalancer.ingress[0].hostname}' 2> /dev/null || true)"
  go_dns="$(ek -n linkforge get ingress go -o jsonpath='{.status.loadBalancer.ingress[0].hostname}' 2> /dev/null || true)"
elif [ "${#args[@]}" -eq 2 ]; then
  app_dns="${args[0]}"
  go_dns="${args[1]}"
else
  die "give either no names or exactly two: APP_DNS GO_DNS"
fi

[ -n "$app_dns" ] && [ -n "$go_dns" ] || die "an Ingress has no address yet (app='${app_dns}' go='${go_dns}'): wait for the ALBs (kubectl -n linkforge get ingress) and try again"
valid='^[a-z0-9]([a-z0-9-]*[a-z0-9])?\.[a-z0-9-]+\.elb\.amazonaws\.com$' # <name>-<digits>.<region>.elb.amazonaws.com
[[ "$app_dns" =~ $valid ]] || die "'$app_dns' does not look like an ALB DNS name"
[[ "$go_dns" =~ $valid ]] || die "'$go_dns' does not look like an ALB DNS name"
if [ "$app_dns" = "$go_dns" ]; then
  die "BOTH Ingresses share ONE load balancer ($app_dns). The two-ALB assumption of HTTP mode failed; nothing was changed. Do not continue: the design needs the other approach (README of envs/eks)."
fi
echo "two different load balancers:"
echo "  app: $app_dns"
echo "  go:  $go_dns"

cd "$GITOPS"
[ "$(git rev-parse --abbrev-ref HEAD)" = main ] || die "the gitops repo is not on main"
[ -z "$(git status --porcelain)" ] || die "the gitops repo has uncommitted changes"
if [ "$PUSH" = 1 ]; then git pull --rebase -q; fi

python3 - "$app_dns" "$go_dns" << 'EOF'
import re, sys
app, go = sys.argv[1], sys.argv[2]
path = "envs/eks/values.yaml"
text = open(path).read()
for key, value in (
    ("SHORT_URL_BASE", f"http://{go}"),
    ("PUBLIC_REDIRECT_HOST", go),
    ("ALLOWED_ORIGINS", f"http://{app}"),
):
    text, n = re.subn(rf"(?m)^(  {key}: ).*$", rf"\g<1>{value}", text)
    if n != 1:
        sys.exit(f"expected exactly one '  {key}:' line in {path}, found {n}")
open(path, "w").write(text)
EOF
git diff --stat
git commit -q -am "chore(eks): point the app at the two ALB DNS names (phase 2)

Generated by scripts/eks-set-hosts.sh."
if [ "$PUSH" = 1 ]; then
  git push -q origin main
  echo "pushed. The pods roll once. Then:  scripts/eks-verify.sh"
else
  echo "committed locally (--no-push)."
fi
