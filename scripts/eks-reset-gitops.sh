#!/usr/bin/env bash
# eks-reset-gitops.sh: put the GitOps repo back into the state a FRESH EKS cluster needs. Run it ONCE before a REBUILD, after a teardown (D91):
#
#   bash scripts/eks-reset-gitops.sh                 (commits and pushes to linkforge-gitops main)
#   bash scripts/eks-reset-gitops.sh --no-push       (commit only; used by the offline test)
#
# Why it exists: the first run leaves the repo in the "enabled" state: the linkforge Application sits in argocd/eks/apps/, there is an
# envs/eks/sealed.values.yaml sealed for the OLD cluster's key (a new cluster cannot decrypt it), and envs/eks/values.yaml holds the
# old load balancer names and your IP addresses. A rebuild started from that state does not work: bootstrap-eks.sh would deploy the app
# at once with a Secret nobody can read and dead host names, Step 8 would find no placeholder to replace, and eks-seal-and-enable.sh would
# refuse ("already enabled"). This script reverses what eks-seal-and-enable.sh, eks-set-hosts.sh and Step 8 did:
#   1 argocd/eks/apps/linkforge.yaml        -> argocd/eks/pending/linkforge.yaml     (the root deploys nothing until the secrets are sealed)
#   2 envs/eks/sealed.values.yaml           -> deleted                                (ciphertext for a cluster that no longer exists)
#   3 SHORT_URL_BASE, PUBLIC_REDIRECT_HOST, ALLOWED_ORIGINS -> pending.invalid        (phase 1 placeholders)
#   4 inbound-cidrs                          -> REPLACE_WITH_YOUR_IP/32                (you set your addresses again in Step 8)
# It is safe to run twice (the second run finds nothing to do) and it changes git only: no AWS, no cluster.
# SAFETY: it refuses while a cluster still answers on $KUBECONFIG, because Argo CD of a LIVE cluster would delete the running app
# the moment the Application leaves apps/ (and the root's auto-sync would follow).
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/eks-common.sh"

GITOPS="${GITOPS_DIR:-$HOME/linkforge-gitops}"
PUSH=1
for arg in "$@"; do
  case "$arg" in
    --no-push) PUSH=0 ;;
    *) die "unknown argument: $arg" ;;
  esac
done

if [ -n "${KUBECONFIG:-}" ] && [ -f "${KUBECONFIG}" ] && command -v kubectl > /dev/null \
  && kubectl --kubeconfig "$KUBECONFIG" get nodes > /dev/null 2>&1; then
  die "a cluster still answers on KUBECONFIG ($KUBECONFIG): Argo CD there would delete the running app. Finish the teardown first (and unset KUBECONFIG), then run this."
fi

step "reset the gitops repo to the fresh-cluster state"
cd "$GITOPS"
[ "$(git rev-parse --abbrev-ref HEAD)" = main ] || die "the gitops repo is not on main"
[ -z "$(git status --porcelain)" ] || die "the gitops repo has uncommitted changes"
if [ "$PUSH" = 1 ]; then git pull --rebase -q; fi

if [ -f argocd/eks/apps/linkforge.yaml ] && [ ! -e argocd/eks/pending/linkforge.yaml ]; then
  mkdir -p argocd/eks/pending
  git mv argocd/eks/apps/linkforge.yaml argocd/eks/pending/linkforge.yaml
  echo "moved the linkforge Application back to argocd/eks/pending/"
fi
if [ -e envs/eks/sealed.values.yaml ]; then
  git rm -q envs/eks/sealed.values.yaml
  echo "removed envs/eks/sealed.values.yaml (sealed for the old cluster)"
fi

python3 - << 'EOF'
import re, sys
path = "envs/eks/values.yaml"
text = open(path).read()
rules = [
    (r"(?m)^(  SHORT_URL_BASE: ).*$", "http://pending.invalid"),
    (r"(?m)^(  PUBLIC_REDIRECT_HOST: ).*$", "pending.invalid"),
    (r"(?m)^(  ALLOWED_ORIGINS: ).*$", "http://pending.invalid"),
    (r"(?m)^(\s+alb\.ingress\.kubernetes\.io/inbound-cidrs: ).*$", "REPLACE_WITH_YOUR_IP/32"),
]
for pattern, value in rules:
    text, n = re.subn(pattern, lambda m: m.group(1) + value, text)
    if n != 1:
        sys.exit("expected exactly one line for %s in %s, found %d" % (pattern, path, n))
open(path, "w").write(text)
EOF

git add -A envs argocd
if [ -z "$(git status --porcelain)" ]; then
  echo "already in the fresh-cluster state: nothing to do"
  exit 0
fi
git diff --cached --stat
git commit -q -m "chore(eks): reset to the fresh-cluster state (app pending, hosts pending.invalid, no sealed values)

Generated by scripts/eks-reset-gitops.sh (D91)."
if [ "$PUSH" = 1 ]; then
  git push -q origin main
  echo "pushed. Next: the rebuild guide (docs/RUNBOOK-eks-run-day.md), Step 3 onward."
else
  echo "committed locally (--no-push)."
fi
