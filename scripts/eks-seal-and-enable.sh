#!/usr/bin/env bash
# eks-seal-and-enable.sh: seal the application secrets against THIS EKS cluster and switch the `linkforge` Application on
# (P9.3). YOU run it, after scripts/bootstrap-eks.sh succeeded and you replaced the IP placeholder in envs/eks/values.yaml:
#
#   export KUBECONFIG=~/.kube/linkforge-eks.yaml
#   export AWS_PROFILE=linkforge                         # only so `terraform output` can read the state bucket
#   scripts/eks-seal-and-enable.sh 2>&1 | tee ~/runlogs/eks-seal-and-enable.log
#
# What it does:
#   1 refuses unless the gitops repo is clean and on main, the IP placeholder is gone and the app is still pending
#   2 reads the RDS host, port, name, user and PASSWORD from `terraform output` (the password only into a shell variable)
#   3 builds DATABASE_URL and a fresh IP_HASH_SECRET and seals each with kubeseal (strict scope: bound to the Secret name
#     `linkforge-db` and the namespace `linkforge`) against the controller of THIS cluster; the values go through pipes
#     and are NEVER printed, written to a file or put on a command line. Only lengths are shown.
#   4 writes envs/eks/sealed.values.yaml (ciphertext only), `git mv`s argocd/eks/pending/linkforge.yaml to argocd/eks/apps/,
#     commits and pushes: the root then creates the linkforge Application, which syncs with the Secret in place.
#
# Options: --no-push (commit only; used by the offline test), --force (overwrite an existing sealed.values.yaml).
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/eks-common.sh"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
GITOPS="${GITOPS_DIR:-$HOME/linkforge-gitops}"
TF_DIR="${TF_DIR:-$REPO_ROOT/infra/terraform/cloud}"
PUSH=1
FORCE=0
for arg in "$@"; do
  case "$arg" in
    --no-push) PUSH=0 ;;
    --force) FORCE=1 ;;
    *) die "unknown argument: $arg" ;;
  esac
done

for tool in terraform kubeseal openssl git; do command -v "$tool" > /dev/null || die "missing tool: $tool"; done
umask 077

step "1/4 checks"
require_eks_cluster
cd "$GITOPS"
[ -f argocd/eks/pending/linkforge.yaml ] || die "argocd/eks/pending/linkforge.yaml not found: already enabled?"
if [ -e envs/eks/sealed.values.yaml ] && [ "$FORCE" = 0 ]; then die "envs/eks/sealed.values.yaml exists (use --force to replace it)"; fi
if grep -q 'REPLACE_' envs/eks/values.yaml; then
  die "envs/eks/values.yaml still contains a REPLACE_ placeholder (inbound-cidrs): put your IP /32 (or 0.0.0.0/0 on purpose) there first"
fi
[ "$(git rev-parse --abbrev-ref HEAD)" = main ] || die "the gitops repo is not on main"
[ -z "$(git status --porcelain)" ] || die "the gitops repo has uncommitted changes"
if [ "$PUSH" = 1 ]; then git pull --rebase -q; fi
ek -n kube-system rollout status deploy/sealed-secrets-controller --timeout=120s

step "2/4 read the database settings from Terraform (nothing secret is printed)"
tf() { terraform -chdir="$TF_DIR" output -raw "$1"; }
db_host="$(tf db_endpoint)"
db_port="$(tf db_port)"
db_name="$(tf db_name)"
db_user="$(tf db_username)"
db_password="$(tf db_password)"
[ -n "$db_host" ] && [ -n "$db_password" ] || die "terraform output returned nothing: has the apply finished, and is AWS_PROFILE set?"
echo "database: $db_user@$db_host:$db_port/$db_name (password: ${#db_password} characters)"

step "3/4 seal against this cluster's key (strict scope: linkforge-db in namespace linkforge)"
seal() {
  # $1 = the value; it travels through a pipe (printf is a shell builtin: not visible in the process list)
  printf '%s' "$1" | kubeseal --raw --scope strict --name linkforge-db --namespace linkforge \
    --controller-name sealed-secrets-controller --controller-namespace kube-system --kubeconfig "$EKS_KUBECONFIG"
}
cipher_url="$(seal "postgresql+asyncpg://${db_user}:${db_password}@${db_host}:${db_port}/${db_name}")"
cipher_hash="$(seal "$(openssl rand -hex 32)")"
unset db_password
[ -n "$cipher_url" ] && [ -n "$cipher_hash" ] || die "kubeseal produced nothing"
echo "sealed DATABASE_URL (${#cipher_url} characters of ciphertext) and IP_HASH_SECRET (${#cipher_hash} characters)"

step "4/4 write the sealed values, enable the Application, commit"
cat > envs/eks/sealed.values.yaml << EOF
# GENERATED by linkforge/scripts/eks-seal-and-enable.sh with this EKS cluster's Sealed Secrets key (strict scope: the Secret
# linkforge-db in namespace linkforge). CIPHERTEXT ONLY: safe to commit, readable only by the controller of this cluster.
# A new cluster has a new key, so this file is thrown away and regenerated with every cluster. Do not edit by hand.
# (The EKS Secret has no POSTGRES_PASSWORD: there is no in-cluster Postgres, RDS holds the password.)
secrets:
  sealed:
    enabled: true
    encryptedData:
      DATABASE_URL: ${cipher_url}
      IP_HASH_SECRET: ${cipher_hash}
EOF
git mv argocd/eks/pending/linkforge.yaml argocd/eks/apps/linkforge.yaml
git add envs/eks/sealed.values.yaml
git commit -q -m "chore(eks): seal the secrets for this cluster and enable the linkforge Application

Generated by scripts/eks-seal-and-enable.sh. Ciphertext only."
if [ "$PUSH" = 1 ]; then
  git push -q origin main
  echo "pushed. Argo CD will create the linkforge Application within a few minutes; watch it:"
else
  echo "committed locally (--no-push). Push it yourself, then watch:"
fi
echo "  kubectl --kubeconfig \"$EKS_KUBECONFIG\" -n argocd get applications -w"
echo "  kubectl --kubeconfig \"$EKS_KUBECONFIG\" -n linkforge get pods,ingress"
echo "When both Ingresses show an ADDRESS: scripts/eks-set-hosts.sh (phase 2)."
